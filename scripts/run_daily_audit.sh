#!/usr/bin/env bash
# FORGE Daily Audit Runner
# 1. Runs daily_audit.py (read-only, zero network)
# 2. Pushes audit_YYYY-MM-DD.{md,json} + audit_latest.{md,json} to the
#    `reports` branch on origin — never touches main or any data branch.
# On failure, writes + pushes a short failure report so the reports branch
# always has today's entry.
#
# Schedule: launchd at 6:30 AM (com.forge.dailyaudit.plist)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
cd "$PROJECT_DIR"

DATE="$(date +%F)"
LOG_DIR="$PROJECT_DIR/logs"
REPORTS_DIR="$PROJECT_DIR/data/reports"
LOG_FILE="$LOG_DIR/audit_${DATE}.log"

mkdir -p "$LOG_DIR" "$REPORTS_DIR"
exec >> "$LOG_FILE" 2>&1

echo "========================================"
echo "FORGE Daily Audit — $DATE $(date +%T)"
echo "========================================"

# ── Python setup ──────────────────────────────────────────────────────────────
if [ -f "$PROJECT_DIR/.venv/bin/activate" ]; then
    source "$PROJECT_DIR/.venv/bin/activate"
    echo "[setup] venv: $VIRTUAL_ENV"
else
    echo "[setup] WARNING: .venv not found, using system python3"
fi
PYTHON="${VIRTUAL_ENV:+$VIRTUAL_ENV/bin/python}"
PYTHON="${PYTHON:-python3}"
echo "[setup] $($PYTHON --version 2>&1)"

AUDIT_MD="$REPORTS_DIR/audit_${DATE}.md"
AUDIT_JSON="$REPORTS_DIR/audit_${DATE}.json"
LATEST_MD="$REPORTS_DIR/audit_latest.md"
LATEST_JSON="$REPORTS_DIR/audit_latest.json"

# ── Step 1: Run audit ─────────────────────────────────────────────────────────
echo ""
echo "[audit] Running daily_audit.py..."
AUDIT_EXIT=0
"$PYTHON" "$SCRIPT_DIR/daily_audit.py" --verbose || AUDIT_EXIT=$?

if [ "$AUDIT_EXIT" -ne 0 ] && [ ! -f "$AUDIT_JSON" ]; then
    echo "[audit] Script failed before writing output — writing failure stub"
    "$PYTHON" - <<PYEOF
import json, os
from datetime import date
today = "${DATE}"
msg = "daily_audit.py failed with exit ${AUDIT_EXIT}. See log: logs/audit_${DATE}.log"
stub = {
    "date": today, "error": msg, "findings": [],
    "zones_checked": 0, "elapsed_seconds": 0,
    "totals": {"high": 0, "medium": 0, "low": 0, "total": 0},
    "new": [], "resolved": [], "by_region": {},
}
rdir = "${REPORTS_DIR}"
with open(os.path.join(rdir, f"audit_{today}.json"), "w") as f: json.dump(stub, f, indent=2)
with open(os.path.join(rdir, f"audit_{today}.md"), "w") as f:
    f.write(f"# FORGE Daily Audit FAILED — {today}\n\n{msg}\n")
with open(os.path.join(rdir, "audit_latest.json"), "w") as f: json.dump(stub, f, indent=2)
with open(os.path.join(rdir, "audit_latest.md"), "w") as f:
    f.write(f"# FORGE Daily Audit FAILED — {today}\n\n{msg}\n")
print("[audit] failure stub written")
PYEOF
fi

# ── Step 2: Push reports to origin/reports ────────────────────────────────────

_push_reports() {
    echo ""
    echo "[push] Pushing reports to origin/reports..."

    git fetch origin --no-tags 2>&1 | grep -v "^$" || true

    local WORKTREE="$PROJECT_DIR/.git/forge-reports-wt"

    # Clean up any stale worktree
    git worktree remove "$WORKTREE" --force 2>/dev/null || true

    # Remove stale local reports branch (safe — we never develop on it)
    git branch -D reports 2>/dev/null || true

    if git rev-parse --verify "origin/reports" >/dev/null 2>&1; then
        git worktree add -b reports "$WORKTREE" origin/reports
    else
        echo "[push] Creating reports branch (first run)..."
        git worktree add --orphan -b reports "$WORKTREE"
        echo "# FORGE Audit Reports" > "$WORKTREE/README.md"
        cat >> "$WORKTREE/README.md" <<'EOF'

Daily data-quality audit for the FORGE lead gen CRM.
Generated by `scripts/run_daily_audit.sh`.
Never contains zone data — read-only findings only.

## Files
- `data/reports/audit_latest.md` — most recent audit (human-readable)
- `data/reports/audit_latest.json` — most recent audit (machine-readable)
- `data/reports/audit_YYYY-MM-DD.*` — daily archives
EOF
    fi

    mkdir -p "$WORKTREE/data/reports"
    for f in "$AUDIT_MD" "$AUDIT_JSON" "$LATEST_MD" "$LATEST_JSON"; do
        [ -f "$f" ] && cp "$f" "$WORKTREE/data/reports/"
    done

    # Build commit message with finding counts
    local COMMIT_MSG="audit: $DATE"
    if command -v python3 > /dev/null && [ -f "$AUDIT_JSON" ]; then
        local COUNTS
        COUNTS=$(python3 -c "
import json, sys
try:
    t = json.load(open('$AUDIT_JSON')).get('totals', {})
    print(f\"HIGH={t.get('high',0)} MED={t.get('medium',0)} LOW={t.get('low',0)}\")
except: pass
" 2>/dev/null || echo "")
        [ -n "$COUNTS" ] && COMMIT_MSG="audit: $DATE — $COUNTS"
    fi

    (
        cd "$WORKTREE"
        git config user.email "audit@forge.local"
        git config user.name "FORGE Audit"
        git add data/reports/ README.md 2>/dev/null || git add data/reports/
        if git diff --cached --quiet 2>/dev/null; then
            echo "[push] No changes — reports already up to date"
        else
            git commit -m "$COMMIT_MSG"
            git push origin HEAD:reports
            echo "[push] Pushed: $COMMIT_MSG"
        fi
    )

    git worktree remove "$WORKTREE" --force 2>/dev/null || true
}

PUSH_EXIT=0
_push_reports || PUSH_EXIT=$?

if [ "$PUSH_EXIT" -ne 0 ]; then
    echo "[push] WARNING: push failed (exit $PUSH_EXIT) — reports are local only"
fi

# ── Summary ───────────────────────────────────────────────────────────────────
echo ""
if [ "$AUDIT_EXIT" -ne 0 ]; then
    echo "AUDIT COMPLETE — FINDINGS REQUIRE ATTENTION (exit $AUDIT_EXIT)"
else
    echo "AUDIT COMPLETE — clean"
fi
echo "Report: $AUDIT_MD"
echo "Log:    $LOG_FILE"

# Always exit 0 so launchd doesn't flag this as a crashed job
exit 0
